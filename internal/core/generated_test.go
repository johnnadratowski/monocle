func generatedRepo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	cmd := exec.Command("git", "init", "-q")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_DIR="+filepath.Join(dir, ".git"), "GIT_WORK_TREE="+dir)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	write := func(p, s string) {
		t.Helper()
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(".gitattributes", "vendor/** linguist-generated\nCargo.lock -linguist-generated\n")
	write("vendor/lib.js", "x\n")
	write("db/q.go", "// Code generated by sqlc. DO NOT EDIT.\n// source: query.sql\npackage db\n")
	write("api/schema.gen.ts", "/**\n * This file was auto-generated by openapi-typescript.\n */\n")
	write("src/app.ts", "export {}\n")
	write("Cargo.lock", "x\n")
	write("min.js", strings.Repeat("a", 10000)+" @generated\n")
	return dir
}

func TestApplyGenerated(t *testing.T) {
	dir := generatedRepo(t)
	files := []types.ChangedFile{
		{Path: "vendor/lib.js"}, {Path: "src/app.ts"}, {Path: "db/q.go"}, {Path: "api/schema.gen.ts"},
		{Path: "Cargo.lock"}, {Path: "gone.gen.ts", Status: types.FileDeleted}, {Path: "go.sum", Status: types.FileDeleted},
		{Path: "min.js"}, {Path: "src/noted.ts"},
	}
	tour := &types.Walkthrough{Generated: map[string]string{"src/noted.ts": "made by x"}}
	got := applyGenerated(dir, files, tour)
	type row struct{ path, why, by, from string }
	var rows []row
	for _, f := range got {
		rows = append(rows, row{f.Path, f.Generated, f.GeneratedBy, f.GeneratedFrom})
	}
	want := []row{
		{"src/app.ts", "", "", ""},
		{"Cargo.lock", "", "", ""}, // the repo said ours
		// A long first line is cut, so a marker 10 KB in is not read.
		{"min.js", "", "", ""},
		{"vendor/lib.js", types.GeneratedByAttr, "", ""},
		{"db/q.go", types.GeneratedHeader, "sqlc", "query.sql"},
		{"api/schema.gen.ts", types.GeneratedName, "openapi-typescript", ""},
		{"gone.gen.ts", types.GeneratedName, "", ""},
		{"go.sum", types.GeneratedLockfile, "", ""},
		{"src/noted.ts", types.GeneratedTour, "", ""},
	}
	if !reflect.DeepEqual(rows, want) {
		t.Errorf("applyGenerated:\n got  %+v\n want %+v", rows, want)
	}
}

// Not a repo: no attribute, but the name and the first lines still count.
func TestApplyGeneratedOutsideARepo(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a.ts"), []byte("// @generated\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	got := applyGenerated(dir, []types.ChangedFile{{Path: "b.ts"}, {Path: "a.ts"}}, nil)
	if got[0].Path != "b.ts" || got[0].Generated != "" || got[1].Generated != types.GeneratedHeader {
		t.Errorf("got %+v", got)
	}
}

// The tour arriving, changing and going marks files generated and then not,
// and the counts the status line reads never wait on a generated file.
func TestATourNoteMarksAFileGeneratedAndItNeverCountsAsUnreviewed(t *testing.T) {
	e, _ := summaryEngine(t)
	unreviewed := func() int {
		e.mu.Lock()
		defer e.mu.Unlock()
		return e.reviewCountsLocked().filesUnreviewed
	}
	generated := func() map[string]string {
		out := map[string]string{}
		for _, f := range e.GetChangedFiles() {
			out[f.Path] = f.Generated
		}
		return out
	}
	before := unreviewed()
	if before == 0 {
		t.Fatal("the test repo should start with unreviewed files")
	}
	msg := tourMsg(types.WalkthroughStop{ID: "1", File: "hello.go"})
	msg.Walkthrough.Generated = map[string]string{"world.go": "made by the world generator"}
	if r := e.handleSetWalkthrough(msg); !r.Success {
		t.Fatal(r.Message)
	}
	if got := generated()["world.go"]; got != types.GeneratedTour {
		t.Errorf("world.go is %q after the tour noted it, want %q", got, types.GeneratedTour)
	}
	if got := unreviewed(); got != before-1 {
		t.Errorf("%d unreviewed with world.go generated, want %d", got, before-1)
	}
	// The note survives a refresh, which judges the files again.
	if _, err := e.RefreshChangedFiles(); err != nil {
		t.Fatal(err)
	}
	if got := generated()["world.go"]; got != types.GeneratedTour {
		t.Errorf("world.go is %q after a refresh, want %q", got, types.GeneratedTour)
	}
	e.handleSetWalkthrough(tourMsg(types.WalkthroughStop{ID: "1", File: "hello.go"}))
	if got := generated()["world.go"]; got != "" {
		t.Errorf("world.go is %q once the tour stops noting it, want hand-written", got)
	}
	if got := unreviewed(); got != before {
		t.Errorf("%d unreviewed after, want %d", got, before)
	}
	// Withdrawing the tour takes its notes with it.
	e.handleSetWalkthrough(msg)
	e.handleSetWalkthrough(&protocol.SetWalkthroughMsg{Type: protocol.TypeSetWalkthrough})
	if got := generated()["world.go"]; got != "" {
		t.Errorf("world.go is %q once the tour is withdrawn, want hand-written", got)
	}
}

func TestAGeneratedNoteForAFileOutsideTheReviewIsAWarning(t *testing.T) {
	w := types.Walkthrough{Generated: map[string]string{"elsewhere.gen.ts": "x", "in.gen.ts": "y"}}
	got := walkthroughWarnings(w, func(p string) bool { return p == "in.gen.ts" }, func(string) bool { return true })
	if len(got) != 1 || !strings.Contains(got[0], "elsewhere.gen.ts") {
		t.Errorf("warnings = %q, want one naming elsewhere.gen.ts", got)
	}
}
