// generatedRepo is a repo whose base commit holds a .gitattributes, generated
// files and hand-written ones; the working tree then changes it the ways a
// change under review could try to fold a file away. It returns the repo and
// the base commit.
func generatedRepo(t *testing.T) (string, string) {
	t.Helper()
	dir := t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GIT_DIR="+filepath.Join(dir, ".git"), "GIT_WORK_TREE="+dir,
			"GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t")
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return strings.TrimSpace(string(out))
	}
	write := func(p, s string) {
		t.Helper()
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	sqlc := "// Code generated by sqlc. DO NOT EDIT.\n// source: query.sql\npackage db\n"
	git("init", "-q")
	write(".gitattributes", "vendor/** linguist-generated\nCargo.lock -linguist-generated\n")
	write("vendor/lib.js", "x\n")
	write("db/q.go", sqlc)
	write("api/schema.gen.ts", "/**\n * This file was auto-generated by openapi-typescript.\n */\n")
	write("src/app.ts", "export {}\n")
	write("src/marked.ts", "export {}\n")
	write("Cargo.lock", "x\n")
	write("min.js", strings.Repeat("a", 10000)+" @generated\n")
	write("old/q.go", sqlc)
	write("gone.gen.ts", "x\n")
	write("src/old-name.ts", "export const n = 1\n")
	git("add", "-A")
	git("commit", "-qm", "base")
	base := git("rev-parse", "HEAD")

	// The change: a .gitattributes line and a header on files the base has
	// (neither counts), new files (their own header and name count, marked
	// so), and two deletions (judged by the base).
	write(".gitattributes", "vendor/** linguist-generated\nCargo.lock -linguist-generated\nsrc/app.ts linguist-generated\n")
	write("src/app.ts", "export const a = 1\n")
	write("src/marked.ts", "// @generated\nexport {}\n")
	write("db/q.go", sqlc+"\nfunc Q() {}\n")
	write("src/new.ts", "// Code generated by mkapi from spec.yaml. DO NOT EDIT.\nexport {}\n")
	write("api/new.gen.ts", "export {}\n")
	write("vendor/new.js", "x\n")
	write("src/plain.ts", "export {}\n")
	git("rm", "-q", "old/q.go", "gone.gen.ts")
	git("mv", "src/old-name.ts", "src/renamed.gen.ts") // a rename's new path is the change's own name
	return dir, base
}

func TestApplyGeneratedReadsWhatTheChangeCannotWrite(t *testing.T) {
	dir, base := generatedRepo(t)
	files := []types.ChangedFile{
		{Path: ".gitattributes", Status: types.FileModified},
		{Path: "vendor/lib.js", Status: types.FileModified}, {Path: "src/app.ts", Status: types.FileModified},
		{Path: "src/marked.ts", Status: types.FileModified}, {Path: "db/q.go", Status: types.FileModified},
		{Path: "api/schema.gen.ts", Status: types.FileModified}, {Path: "Cargo.lock", Status: types.FileModified},
		{Path: "min.js", Status: types.FileModified},
		{Path: "old/q.go", Status: types.FileDeleted}, {Path: "gone.gen.ts", Status: types.FileDeleted},
		{Path: "src/new.ts", Status: types.FileAdded}, {Path: "api/new.gen.ts", Status: types.FileAdded},
		{Path: "vendor/new.js", Status: types.FileAdded}, {Path: "src/plain.ts", Status: types.FileAdded},
		{Path: "src/renamed.gen.ts", Status: types.FileRenamed},
	}
	got := applyGenerated(dir, base, files)
	type row struct {
		path, why     string
		own, new      bool
		by, from, top string
	}
	var rows []row
	for _, f := range got {
		top, _, _ := strings.Cut(f.GeneratedHead, "\n")
		rows = append(rows, row{f.Path, f.Generated, f.GeneratedOwn, f.GeneratedNew, f.GeneratedBy, f.GeneratedFrom, top})
	}
	want := []row{
		{".gitattributes", "", false, false, "", "", ""},
		{"src/app.ts", "", false, false, "", "", ""},    // the change's own .gitattributes line does not count
		{"src/marked.ts", "", false, false, "", "", ""}, // a header the change adds to a file the base has does not
		{"Cargo.lock", "", false, false, "", "", ""},    // the base says ours
		{"min.js", "", false, false, "", "", ""},        // a long first line is cut: a marker 10 KB in is not read
		{"src/plain.ts", "", false, true, "", "", "export {}"},
		{"vendor/lib.js", types.GeneratedByAttr, false, false, "", "", ""},
		{"db/q.go", types.GeneratedHeader, false, false, "sqlc", "query.sql", ""}, // the base has the header too
		{"api/schema.gen.ts", types.GeneratedName, false, false, "openapi-typescript", "", ""},
		{"old/q.go", types.GeneratedHeader, false, false, "sqlc", "query.sql", ""}, // deleted: the base's header
		{"gone.gen.ts", types.GeneratedName, false, false, "", "", ""},
		{"src/new.ts", types.GeneratedHeader, true, true, "mkapi", "spec.yaml", "// Code generated by mkapi from spec.yaml. DO NOT EDIT."},
		{"api/new.gen.ts", types.GeneratedName, true, true, "", "", "export {}"},
		{"vendor/new.js", types.GeneratedByAttr, false, true, "", "", "x"}, // new, but the base's attribute says so
		{"src/renamed.gen.ts", types.GeneratedName, true, true, "", "", "export const n = 1"},
	}
	if !reflect.DeepEqual(rows, want) {
		t.Errorf("applyGenerated:\n got  %+v\n want %+v", rows, want)
	}
}

// No base to read: every file is judged by its own signals, each marked so.
func TestApplyGeneratedWithNoBaseMarksEveryOneOwn(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a.ts"), []byte("// @generated\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	got := applyGenerated(dir, "", []types.ChangedFile{{Path: "b.ts"}, {Path: "a.ts"}})
	if got[0].Path != "b.ts" || got[0].Generated != "" || got[1].Generated != types.GeneratedHeader || !got[1].GeneratedOwn {
		t.Errorf("got %+v", got)
	}
}

// A generated file counts as unreviewed until it is marked: the change under
// review must not be able to take a file out of review (John, 2026-10-31).
func TestAGeneratedFileCountsAsUnreviewedUntilMarked(t *testing.T) {
	e, _ := summaryEngine(t)
	unreviewed := func() int {
		e.mu.Lock()
		defer e.mu.Unlock()
		return e.reviewCountsLocked().filesUnreviewed
	}
	before := unreviewed()
	if before == 0 {
		t.Fatal("the test repo should start with unreviewed files")
	}
	e.mu.Lock()
	e.current.ChangedFiles[0].Generated = types.GeneratedLockfile
	e.mu.Unlock()
	if got := unreviewed(); got != before {
		t.Errorf("%d unreviewed with a generated file unmarked, want %d", got, before)
	}
	e.mu.Lock()
	e.current.ChangedFiles[0].Reviewed = true
	e.mu.Unlock()
	if got := unreviewed(); got != before-1 {
		t.Errorf("%d unreviewed once it is marked, want %d", got, before-1)
	}
}

// A tour's note never makes a file generated: it is only the card's text for a
// file the rule already calls generated. A note on any other file is a warning.
func TestATourNoteNeverMakesAFileGenerated(t *testing.T) {
	e, _ := summaryEngine(t)
	msg := tourMsg(types.WalkthroughStop{ID: "1", File: "hello.go"})
	msg.Walkthrough.Generated = map[string]string{"world.go": "made by the world generator"}
	r := e.handleSetWalkthrough(msg)
	if !r.Success {
		t.Fatal(r.Message)
	}
	for _, f := range e.GetChangedFiles() {
		if f.IsGenerated() {
			t.Errorf("%s is %q after the tour noted world.go, want every file hand-written", f.Path, f.Generated)
		}
	}
	if len(r.Warnings) != 1 || !strings.Contains(r.Warnings[0], "world.go is not generated") {
		t.Errorf("warnings = %q, want one saying world.go's note shows nowhere", r.Warnings)
	}
	if _, err := e.RefreshChangedFiles(); err != nil {
		t.Fatal(err)
	}
	for _, f := range e.GetChangedFiles() {
		if f.IsGenerated() {
			t.Errorf("%s is %q after a refresh, want hand-written", f.Path, f.Generated)
		}
	}
}

func TestAGeneratedNoteShowingNowhereIsAWarning(t *testing.T) {
	w := types.Walkthrough{Generated: map[string]string{"elsewhere.gen.ts": "x", "in.gen.ts": "y", "in.ts": "z"}}
	inReview := func(p string) bool { return p != "elsewhere.gen.ts" }
	got := walkthroughWarnings(w, inReview, func(string) bool { return true }, func(p string) bool { return p == "in.gen.ts" })
	if len(got) != 2 || !strings.Contains(got[0], "elsewhere.gen.ts is not in the review") ||
		!strings.Contains(got[1], "in.ts is not generated") {
		t.Errorf("warnings = %q, want elsewhere.gen.ts not in the review, then in.ts not generated", got)
	}
}
