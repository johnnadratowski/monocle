// The tour's note makes a file generated even when the rule says not; the
// rule's reason, when it has one, is kept.
func TestMarkGenerated(t *testing.T) {
	files := []ChangedFile{
		{Path: "src/a.ts"},
		{Path: "pnpm-lock.yaml", Generated: GeneratedLockfile},
		{Path: "src/b.ts"},
		{Path: "src/was-noted.ts", Generated: GeneratedTour},
		{Path: "src/c.ts"},
	}
	w := &Walkthrough{Generated: map[string]string{"src/b.ts": "made by x", "pnpm-lock.yaml": "the lockfile"}}
	got := MarkGenerated(files, w)
	var order, reasons []string
	for _, f := range got {
		order = append(order, f.Path)
		reasons = append(reasons, f.Generated)
	}
	// Hand-written first, in their order; the generated after, in theirs.
	if want := []string{"src/a.ts", "src/was-noted.ts", "src/c.ts", "pnpm-lock.yaml", "src/b.ts"}; !reflect.DeepEqual(order, want) {
		t.Errorf("order %q, want %q", order, want)
	}
	if want := []string{"", "", "", GeneratedLockfile, GeneratedTour}; !reflect.DeepEqual(reasons, want) {
		t.Errorf("reasons %q, want %q", reasons, want)
	}
	if got := MarkGenerated(nil, nil); got != nil {
		t.Errorf("MarkGenerated(nil) = %v", got)
	}
}

func TestNormalizeWalkthroughTidiesGeneratedNotes(t *testing.T) {
	got, err := NormalizeWalkthrough(Walkthrough{Stops: []WalkthroughStop{{ID: "a"}}, Generated: map[string]string{
		" ./docs/swagger.json ": "  The spec, from swag.  ",
		"empty.gen.ts":          "   ",
		"  ":                    "no path",
	}})
	if err != nil {
		t.Fatal(err)
	}
	if want := map[string]string{"docs/swagger.json": "The spec, from swag."}; !reflect.DeepEqual(got.Generated, want) {
		t.Errorf("Generated = %q, want %q", got.Generated, want)
	}
	got, _ = NormalizeWalkthrough(Walkthrough{Stops: []WalkthroughStop{{ID: "a"}}})
	if got.Generated != nil {
		t.Errorf("a tour with no notes has Generated %q, want nil", got.Generated)
	}
}
