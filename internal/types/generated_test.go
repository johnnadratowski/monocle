// The card names what made the file, from its header, when the header says.
func TestGeneratorOf(t *testing.T) {
	cases := []struct{ head, gen, src string }{
		{"/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */", "openapi-typescript", ""},
		{"// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.27.0\n// source: query.sql\n", "sqlc", "query.sql"},
		{"// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: api/v1/api.proto", "protoc-gen-go", "api/v1/api.proto"},
		{"# @generated by uv from pyproject.toml", "uv", "pyproject.toml"},
		{"// Code generated by MockGen. DO NOT EDIT.\n// Source: store.go", "MockGen", "store.go"},
		{"// @generated", "", ""},
		{"package main", "", ""},
		{"a\nb\nc\nd\ne\n// Code generated by late. DO NOT EDIT.", "", ""},
	}
	for _, c := range cases {
		gen, src := GeneratorOf(c.head)
		if gen != c.gen || src != c.src {
			t.Errorf("GeneratorOf(%q) = (%q, %q), want (%q, %q)", c.head, gen, src, c.gen, c.src)
		}
	}
}

// lockDiff is a one-hunk diff of a lockfile from +/-/space prefixed lines.
func lockDiff(path, body string) *DiffResult {
	var h DiffHunk
	for _, ln := range strings.Split(strings.TrimPrefix(body, "\n"), "\n") {
		if ln == "" {
			continue
		}
		kind := DiffLineContext
		switch ln[0] {
		case '+':
			kind = DiffLineAdded
		case '-':
			kind = DiffLineRemoved
		}
		h.Lines = append(h.Lines, DiffLine{Kind: kind, Content: ln[1:]})
	}
	return &DiffResult{Path: path, Hunks: []DiffHunk{h}}
}

