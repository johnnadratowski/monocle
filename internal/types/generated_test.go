// SortGenerated puts the generated files after the rest, each in the order
// they came, and judges nothing: a tour's note never makes a file generated.
func TestSortGenerated(t *testing.T) {
	files := []ChangedFile{
		{Path: "src/a.ts"},
		{Path: "pnpm-lock.yaml", Generated: GeneratedLockfile},
		{Path: "src/b.ts"},
		{Path: "api.gen.ts", Generated: GeneratedName, GeneratedOwn: true},
		{Path: "src/c.ts"},
	}
	got := SortGenerated(files)
	var order, reasons []string
	for _, f := range got {
		order = append(order, f.Path)
		reasons = append(reasons, f.Generated)
	}
	if want := []string{"src/a.ts", "src/b.ts", "src/c.ts", "pnpm-lock.yaml", "api.gen.ts"}; !reflect.DeepEqual(order, want) {
		t.Errorf("order %q, want %q", order, want)
	}
	if want := []string{"", "", "", GeneratedLockfile, GeneratedName}; !reflect.DeepEqual(reasons, want) {
		t.Errorf("reasons %q, want %q", reasons, want)
	}
	if got := SortGenerated(nil); got != nil {
		t.Errorf("SortGenerated(nil) = %v", got)
	}
}

// The change-cases table of design/generated-files.md, row for row (stage's
// check-tour answers the same rows): what a file is judged from must not come
// from the change under review. The attribute is the BASE's; a file at the
// base counts by a header only when the base's version has it too; a new file
// counts by its own header or name, and says so (own).
